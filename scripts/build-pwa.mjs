import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

// An explicit allowlist prevents caching API, OAuth, signed URLs or booking data.
const assets = (await readdir("dist/assets"))
  .filter((name) => /\.(?:js|css|woff2?|webp)$/.test(name))
  .map((name) => `/assets/${name}`);
const files = [
  ...assets,
  "/offline.html",
  "/offline.css",
  "/offline.js",
  "/manifest.webmanifest",
  "/favicon.svg",
  "/icons/icon-192.png",
  "/icons/icon-512.png",
  "/icons/maskable-512.png",
  "/icons/apple-touch-icon.png",
].sort();
const hash = createHash("sha256");
for (const path of files) {
  hash.update(path);
  hash.update(await readFile(`dist${path}`));
}
const version = hash.digest("hex").slice(0, 16);
const worker = `/* Generated by build-pwa.mjs. Static public assets only. */
const CACHE = 'beautyhub-static-${version}';
const FILES = ${JSON.stringify(files)};
const ALLOWED = new Set(FILES);
const findStatic = async request => (await caches.open(CACHE)).match(request);
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES.map(path => new Request(path, {cache: 'reload', credentials: 'omit'})))));
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = (await caches.keys()).filter(name => name.startsWith('beautyhub-static-'));
    // Keep the previous build for tabs that are still open during an update.
    const stale = names.filter(name => name !== CACHE).slice(0, -1);
    await Promise.all(stale.map(name => caches.delete(name)));
    await self.clients.claim();
  })());
});
self.addEventListener('message', event => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});
self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    // Never store a navigated response, query parameters, OAuth code or tokens.
    event.respondWith(fetch(new Request(request, {cache:'no-store'})).catch(async () =>
      (await findStatic('/offline.html')) || new Response('Không thể kết nối. Vui lòng thử lại.', {status:503,headers:{'Content-Type':'text/plain;charset=utf-8'}})));
  } else if (!url.search && ALLOWED.has(url.pathname)) {
    event.respondWith(findStatic(request).then(cached => cached || fetch(request)));
  }
});
`;
await writeFile("dist/sw.js", worker);
await writeFile(
  "dist/pwa-build.json",
  JSON.stringify({ version, staticFiles: files.length }),
);
console.log(
  `PWA built: ${version}, ${files.length} public static files; API/auth data excluded.`,
);
